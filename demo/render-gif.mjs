function drawText(pixels, text, row, col, color) {
  for (let i = 0; i < text.length && col + i < COLS; i += 1) {
    const cols = GLYPHS[text[i]] ?? GLYPHS["?"];
    for (let x = 0; x < 5; x += 1) {
      const bits = cols[x] ?? 0;
      for (let y = 0; y < 7; y += 1) {
        if (bits & (1 << y)) {
          const px = PAD + (col + i) * CW + x;
          const py = PAD + row * CH + y;
          if (px >= 0 && px < WIDTH && py >= 0 && py < HEIGHT) {
            pixels[py * WIDTH + px] = color;
          }
        }
      }
    }
  }
}

function lzw(indexes, minCode = 2) {
  const clear = 1 << minCode;
  const eoi = clear + 1;
  /** @type {Map<string, number>} */
  const dict = new Map();
  let next = eoi + 1;
  let size = minCode + 1;
  const bytes = [];
  let acc = 0;
  let n = 0;
  const put = (code) => {
    acc |= code << n;
    n += size;
    while (n >= 8) {
      bytes.push(acc & 0xff);
      acc >>= 8;
      n -= 8;
    }
  };
  const reset = () => {
    dict.clear();
    next = eoi + 1;
    size = minCode + 1;
    put(clear);
  };
  reset();
  let w = String.fromCharCode(indexes[0] & 3);
  for (let i = 1; i < indexes.length; i += 1) {
    const k = String.fromCharCode(indexes[i] & 3);
    const wk = w + k;
    if (dict.has(wk)) {
      w = wk;
      continue;
    }
    put(w.length === 1 ? w.charCodeAt(0) : dict.get(w));
    if (next < 4096) {
      dict.set(wk, next);
      if (next === 1 << size && size < 12) size += 1;
      next += 1;
    } else {
      reset();
    }
    w = k;
  }
  put(w.length === 1 ? w.charCodeAt(0) : dict.get(w));
  put(eoi);
  if (n) bytes.push(acc & 0xff);

  const packed = [minCode];
  for (let i = 0; i < bytes.length; i += 255) {
    const chunk = bytes.slice(i, i + 255);
    packed.push(chunk.length, ...chunk);
  }
  packed.push(0);
  return Uint8Array.from(packed);
}

function encodeGif(frames) {
  const gctSize = 1; // 2^(1+1) = 4 colors
  const header = Uint8Array.from([
    0x47,
    0x49,
    0x46,
    0x38,
    0x39,
    0x61,
    WIDTH & 0xff,
    (WIDTH >> 8) & 0xff,
    HEIGHT & 0xff,
    (HEIGHT >> 8) & 0xff,
    0x80 | gctSize,
    0x00,
    0x00,
    ...PALETTE,
    0x21,
    0xff,
    0x0b,
    ...Buffer.from("NETSCAPE2.0"),
    0x03,
    0x01,
    0x00,
    0x00,
    0x00,
  ]);
  const parts = [header];
  for (const frame of frames) {
    const pixels = new Uint8Array(WIDTH * HEIGHT);
    frame.lines.forEach((line, i) =>
      drawText(pixels, line[1], i + 1, 1, line[0]),
    );
    parts.push(
      Uint8Array.of(
        0x21,
        0xf9,
        0x04,
        0x04,
        frame.delay & 0xff,
        (frame.delay >> 8) & 0xff,
        0,
        0,
      ),
      Uint8Array.of(
        0x2c,
        0,
        0,
        0,
        0,
        WIDTH & 0xff,
        (WIDTH >> 8) & 0xff,
        HEIGHT & 0xff,
        (HEIGHT >> 8) & 0xff,
        0,
      ),
      lzw(pixels),
    );
  }
  parts.push(Uint8Array.of(0x3b));
  const size = parts.reduce((n, p) => n + p.length, 0);
  const out = new Uint8Array(size);
  let o = 0;
  for (const p of parts) {
    out.set(p, o);
    o += p.length;
  }
  return out;
}

export function renderQuickstartGif() {
  return encodeGif(FRAMES);
}

if (import.meta.main) {
  const gif = renderQuickstartGif();
  writeFileSync(OUT, gif);
  console.log(`wrote ${OUT} (${gif.length} bytes)`);
}
